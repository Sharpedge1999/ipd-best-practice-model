#!/usr/bin/env python3
"""Render register/iPD_Requirements_Register.md (deterministic, no timestamps).

Run: python -I tools/render_register.py
Inputs: synthesis/requirements.yaml, synthesis/merged_findings.yaml, synthesis/conflicts.md,
        synthesis/l3_cut.md, contracts/source_registry.yaml
Exit 1 if the output contains an em dash, en dash or middle dot.
"""
import re
import sys
from collections import Counter, OrderedDict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SYN = ROOT / "synthesis"
OUT = ROOT / "register" / "iPD_Requirements_Register.md"
STEPS = [f"A{i}" for i in range(1, 9)]
BIND_ORDER = ["binding-law", "binding-ICH", "guidance", "best-practice", "verify-binding"]
# Publisher names of industry sources are shown by source key (no company names in the text).
FORBIDDEN = (chr(0x2014), chr(0x2013), chr(0x00B7))  # em dash, en dash, middle dot
SUBST = [("TransCelerate", "TCB")] + [(ch, "-") for ch in FORBIDDEN]


def clean(text):
    text = "" if text is None else str(text)
    for a, b in SUBST:
        text = text.replace(a, b)
    return text


def cell(text):
    return clean(text).replace("|", "/").replace("\n", " ").strip()


def load_yaml(path):
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def parse_fields(block):
    """'- **Name:** value' lines; continuation lines (indented) are appended."""
    fields, current = OrderedDict(), None
    for line in block.splitlines():
        m = re.match(r"^- \*\*(.+?):\*\*\s*(.*)$", line)
        if m:
            current = m.group(1)
            fields[current] = m.group(2).strip()
        elif current and line.startswith("  "):
            fields[current] += "\n" + line.strip()
    return fields


def parse_sections(text, pattern):
    parts = re.split(r"^## ", text, flags=re.M)
    out = []
    for p in parts[1:]:
        head, _, body = p.partition("\n")
        m = re.match(pattern, head.strip())
        if m:
            out.append((m, body))
    return out


def strip_markers(text):
    return re.sub(r"<!--/?[A-Z]+:A\d-->", "", text)


def main():
    reqs = load_yaml(SYN / "requirements.yaml")
    merged = {f["id"]: f for f in load_yaml(SYN / "merged_findings.yaml")}
    registry = load_yaml(ROOT / "contracts" / "source_registry.yaml")
    reg = OrderedDict((s["key"], s) for s in registry["sources"])
    l3_text = (SYN / "l3_cut.md").read_text(encoding="utf-8")
    conf_text = (SYN / "conflicts.md").read_text(encoding="utf-8")

    steps = OrderedDict()
    for m, body in parse_sections(l3_text, r"^(A\d) - (.+)$"):
        steps[m.group(1)] = (m.group(2), parse_fields(body))
    flow_section = re.search(r"## L3 flow\n(.*?)\n## ", l3_text, flags=re.S).group(1)
    flow_code = re.search(r"```\n(.*?)\n```", flow_section, flags=re.S)
    flow = flow_code.group(1).strip()
    flow_notes = flow_section[flow_code.end():].strip()
    conflicts = []
    for m, body in parse_sections(conf_text, r"^(C-\d+) (.+)$"):
        conflicts.append((m.group(1), m.group(2), parse_fields(body)))

    src_count = Counter(f["src"] for f in merged.values())
    L = []
    add = L.append
    add("# iPD Requirements Register - best-practice model of important protocol deviation management")
    add("")
    add("Status: 07 Nov 2026. Validation V1 round 3 verdict: 'pass with documented exceptions' (FLW-09/SCP-02 at L4-03 S1, "
        "see conflict C-27; validation/report_r3.md). Blind verification X1: 427/427 findings confirmed after re-check "
        "(verification/X1_recheck.yaml; corrections in synthesis/changes_X1.md).")
    add("")
    add(f"Source registry: {clean(registry.get('reconciled_by', ''))}. Generated by `tools/render_register.py` from "
        "`synthesis/requirements.yaml`, `synthesis/merged_findings.yaml`, `synthesis/conflicts.md`, "
        "`synthesis/l3_cut.md` and `contracts/source_registry.yaml`. Do not edit by hand.")
    add("")

    # ---------------------------------------------------------------- (1)
    add("## 1. Scope, method and sources read")
    add("")
    add("**Scope.** Best-practice (outside-in) reference process for managing important protocol deviations (iPDs) in "
        "clinical trials of medicinal products, derived from ICH guidelines, EU and US regulation and guidance, and "
        "recognised industry practice. Jurisdictions: ICH, EU, US; UK and medical devices are out of scope and recorded "
        "as gaps. Process boundary: from 'CtQ factors identified' to 'iPDs reported in CSR and records archived'. Pools: "
        "Sponsor (lanes Sponsor and Monitor), Investigator/institution (expanded), IRB/IEC and Regulatory authority "
        "(collapsed). 'CSR' means clinical study report; 'EU CTR' means Regulation (EU) No 536/2014.")
    add("")
    add("**Method.** Five research stems (R1 ICH E6(R3), R2 other ICH, R3 EU, R4 US, R5 industry and data standards) "
        "recorded one atomic obligation per finding with source, location, page, binding class and party. The synthesis "
        "merged findings that state the same obligation for the same party into one requirement (REQ); EU, US and ICH "
        "obligations stay separate where trigger, deadline or recipient differ. A REQ's binding class is the strongest "
        "of its findings (binding-law > binding-ICH > guidance > best-practice); ICH guidelines are never binding-law and "
        "carry their regional route; a REQ is marked DRAFT only if its strongest findings are all draft guidance, and "
        "draft guidance is never the only basis of a binding REQ. A finding marked dup_of restates a canonical finding "
        "of the same REQ. A REQ's modal is the strongest modal among the findings of its binding class (must > should > may > definition > example); 'may' REQs are stated as permissions. Every REQ is mapped to one L3 step, or marked interface or out of scope with a reason. "
        "Publishers of industry sources are shown by source key; no client, company or person names are used in the text.")
    add("")
    by_stem = Counter(fid.split("-")[0] for fid in merged)
    by_bind = Counter(f["binding"] for f in merged.values())
    add(f"**Counts.** Findings: {len(merged)} ("
        + ", ".join(f"{k} {by_stem[k]}" for k in sorted(by_stem)) + "); by binding class: "
        + ", ".join(f"{b} {by_bind[b]}" for b in BIND_ORDER if by_bind[b]) + f"; draft {sum(1 for f in merged.values() if f.get('draft'))}; "
        f"dup_of {sum(1 for f in merged.values() if f.get('dup_of'))}; corrected after blind verification X1 "
        f"{sum(1 for f in merged.values() if (f.get('x1') or {}).get('corrected'))} (x1 field; log in synthesis/changes_X1.md). "
        f"Requirements: {len(reqs)} ("
        + ", ".join(f"{s} {n}" for s, n in sorted(Counter(r['status'] for r in reqs).items())) + "); by binding class: "
        + ", ".join(f"{b} {Counter(r['binding'] for r in reqs)[b]}" for b in BIND_ORDER if Counter(r['binding'] for r in reqs)[b])
        + f"; draft {sum(1 for r in reqs if r['draft'])}.")
    add("")
    add("**Sources read** (version, retrieval channel and date; full list in section 7):")
    add("")
    add("| Key | Version read | Retrieval | URL status | Findings |")
    add("|---|---|---|---|---|")
    for k, s in reg.items():
        add(f"| {cell(k)} | {cell(s.get('version_read', ''))} | {cell(s.get('retrieval', ''))} | "
            f"{cell(s.get('url_status', ''))} | {src_count.get(k, 0)} |")
    add("")
    add("**Gaps:**")
    add("")
    for g in registry.get("gaps", []):
        add(f"- {clean(g)}")
    add("")

    # ---------------------------------------------------------------- (2)
    add("## 2. L3 cut summary")
    add("")
    add("```")
    add(clean(flow))
    add("```")
    add("")
    if flow_notes:
        add(clean(flow_notes))
        add("")
    add("| Step | Label | Trigger (start event) | Outcomes (end events) | Pools and lanes | REQs | As-Is comparability | L4 size |")
    add("|---|---|---|---|---|---|---|---|")
    for sid, (label, fl) in steps.items():
        n = sum(1 for r in reqs if r["status"] == "in_scope" and r["l3_step"] == sid)
        add(f"| {sid} | {cell(label)} | {cell(fl.get('Trigger (start event)', ''))} | "
            f"{cell(fl.get('Outcomes (end events)', ''))} | {cell(fl.get('Pools and lanes', ''))} | {n} | "
            f"{cell(fl.get('As-Is comparability', ''))} | {cell(fl.get('L4 size estimate', ''))} |")
    add("")
    add("Message flows to external pools per step, with binding basis:")
    add("")
    for sid, (label, fl) in steps.items():
        mf = fl.get("Message flows", "")
        items = [x.lstrip("- ").strip() for x in mf.split("\n") if x.strip()]
        add(f"- **{sid}:** " + ("; ".join(clean(i) for i in items) if items else "none"))
    add("")

    # ---------------------------------------------------------------- (3)
    def sources(r):
        seen, out = set(), []
        for fid in r["findings"]:
            f = merged[fid]
            key = (f["src"], f["loc"], f.get("page", ""))
            if key in seen:
                continue
            seen.add(key)
            page = f" (p. {f['page']})" if f.get("page") else ""
            out.append(f"{f['src']} {f['loc']}{page}")
        return "; ".join(out)

    def binding(r):
        return r["binding"] + (" DRAFT" if r["draft"] else "")

    add("## 3. Requirements per L3 step")
    add("")
    for sid in STEPS:
        label = steps.get(sid, ("",))[0]
        rs = [r for r in reqs if r["status"] == "in_scope" and r["l3_step"] == sid]
        c = Counter(r["binding"] for r in rs)
        add(f"### {sid} - {clean(label)}")
        add("")
        add(f"{len(rs)} REQs: " + ", ".join(f"{b} {c[b]}" for b in BIND_ORDER if c[b])
            + f" (DRAFT {sum(1 for r in rs if r['draft'])}).")
        add("")
        add("| REQ | Requirement | Modal | Party | Trigger | Deadline | Recipient | Record | Binding | Jurisdiction | Sources (key loc page) |")
        add("|---|---|---|---|---|---|---|---|---|---|---|")
        for r in rs:
            add(f"| {r['id']} | {cell(r['statement'])} | {cell(r.get('modal', ''))} | {cell(r['party_norm'])} | {cell(r['trigger'])} | "
                f"{cell(r['deadline'])} | {cell(r['recipient'])} | {cell(r['record'])} | {cell(binding(r))} | "
                f"{cell(', '.join(r['jurisdiction']))} | {cell(sources(r))} |")
        add("")

    # ---------------------------------------------------------------- (4)
    add("## 4. Out-of-scope and interface requirements")
    add("")
    add("### Interface requirements (placeholder at the named step)")
    add("")
    add("| REQ | Requirement | Modal | Near step | Reason | Party | Binding | Jurisdiction | Sources (key loc page) |")
    add("|---|---|---|---|---|---|---|---|---|")
    for r in [r for r in reqs if r["status"] == "interface"]:
        add(f"| {r['id']} | {cell(r['statement'])} | {cell(r.get('modal', ''))} | {cell(r['l3_step'])} | {cell(r['reason'])} | {cell(r['party_norm'])} | "
            f"{cell(binding(r))} | {cell(', '.join(r['jurisdiction']))} | {cell(sources(r))} |")
    add("")
    add("### Out-of-scope requirements")
    add("")
    add("| REQ | Requirement | Modal | Reason | Party | Binding | Jurisdiction | Sources (key loc page) |")
    add("|---|---|---|---|---|---|---|---|")
    for r in [r for r in reqs if r["status"] == "out_of_scope"]:
        add(f"| {r['id']} | {cell(r['statement'])} | {cell(r.get('modal', ''))} | {cell(r['reason'])} | {cell(r['party_norm'])} | "
            f"{cell(binding(r))} | {cell(', '.join(r['jurisdiction']))} | {cell(sources(r))} |")
    add("")

    # ---------------------------------------------------------------- (5)
    add("## 5. Conflicts")
    add("")
    add("| ID | Conflict | Findings | Handling in the model | Decision |")
    add("|---|---|---|---|---|")
    for cid, title, fl in conflicts:
        sides = " ".join(v for k, v in fl.items() if k.startswith("Side") or k == "Tension")
        fids = set(re.findall(r"R\d-\d{3}", sides))
        for a_stem, a_num, b_stem, b_num in re.findall(r"(R\d)-(\d{3}) to (R\d)-(\d{3})", sides):
            if a_stem == b_stem:
                fids.update(f"{a_stem}-{n:03d}" for n in range(int(a_num), int(b_num) + 1))
        fids = sorted(f for f in fids if f in merged)
        add(f"| {cid} | {cell(title)} | {cell(', '.join(fids))} | {cell(fl.get('Handling in the model', ''))} | "
            f"{cell(fl.get('Decision', fl.get('User decision', '')))} |")
    add("")

    # ---------------------------------------------------------------- (6)
    add("## 6. Open [verify] items")
    add("")
    n_items = sum(len(r["verify"]) for r in reqs)
    add(f"{n_items} items on {sum(1 for r in reqs if r['verify'])} REQs (finding-level items carry the finding id in brackets).")
    add("")
    for r in reqs:
        if r["verify"]:
            add(f"- **{r['id']}** ({r['status']}{', ' + r['l3_step'] if r['l3_step'] else ''}): "
                + "; ".join(clean(v) for v in r["verify"]))
    add("")

    # ---------------------------------------------------------------- (7)
    add("## 7. Source list")
    add("")
    add("| Key | Title | Jurisdiction | Default binding | Draft | URL | URL status | Local text |")
    add("|---|---|---|---|---|---|---|---|")
    for k, s in reg.items():
        add(f"| {cell(k)} | {cell(s.get('title', ''))} | {cell(s.get('jurisdiction', ''))} | {cell(s.get('binding_default', ''))} | "
            f"{'yes' if s.get('draft') else 'no'} | {cell(s.get('url', ''))} | {cell(s.get('url_status', ''))} | "
            f"{cell(s.get('local_text') or '-')} |")
    add("")

    text = "\n".join(L) + "\n"
    bad = [hex(ord(ch)) for ch in FORBIDDEN if ch in text]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text)} chars, {len(reqs)} REQs, {len(conflicts)} conflicts, {len(steps)} steps)")
    if bad:
        print("ERROR: forbidden characters in output:", bad)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
