#!/usr/bin/env python3
"""Append the results of one validation layer to validation/report_<round>.json and regenerate report_<round>.md.

The JSON report is a list of records:
  - error records: rule_id, layer, model, element, message, severity (MUST|SHOULD), owner, status
  - one summary record per layer: {"record": "summary", "layer": ..., "passed": [...], "counts": {...}, ...}
Re-running a layer replaces that layer's records (idempotent), other layers are kept, so an interrupted
run never loses finished layers.

Usage: python -I tools/validate/v1_report.py --round r1 --layer L0 --src /tmp/x.json [--src ...] [--note "..."]
       python -I tools/validate/v1_report.py --round r1 --md-only
"""
import argparse
import datetime
import json
import os
from collections import Counter, OrderedDict

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
VAL = os.path.join(ROOT, "validation")
LAYERS = ["L0", "L1", "L2", "L3", "L4", "REVIEW", "L5"]
FIELDS = ["rule_id", "layer", "model", "element", "message", "severity", "owner", "status"]
LAYER_TITLE = {
    "L0": "L0 Contract (owner B1)",
    "L1": "L1 Syntax (owner B2)",
    "L2": "L2 Graph (owner B1)",
    "L3": "L3 Auto rules (owner B1; LAY-04 and DI: B2)",
    "L4": "L4 Traceability (owner B1, Y1 where the requirement is wrong)",
    "REVIEW": "Review rules (judgement)",
    "L5": "L5 Render (owner W1)",
}


def load(path):
    if os.path.exists(path):
        return json.load(open(path, encoding="utf-8"))
    return []


def norm(e):
    d = OrderedDict()
    for k in FIELDS:
        d[k] = e.get(k, "open" if k == "status" else "")
    for k, v in e.items():
        if k not in d:
            d[k] = v
    return d


def counts(errs):
    c = Counter()
    for e in errs:
        doc = e.get("status", "open") != "open"
        c["%s%s" % (e["severity"], " documented" if doc else "")] += 1
    return dict(sorted(c.items()))


def write_md(rnd, recs):
    out = []
    out.append("# V1 validation report - round %s" % rnd[1:])
    out.append("")
    out.append("Generated by `tools/validate/v1_report.py` from `validation/report_%s.json` (the JSON is authoritative). "
               "Validator: V1 (independent). Severity MUST or SHOULD; status `open` needs a repair by the owner, "
               "`documented-*` is a SHOULD deviation or exception already justified in `spec/notes.md` (no repair needed, listed for completeness)." % rnd)
    out.append("")
    errs = [r for r in recs if r.get("record") not in ("summary", "comparison", "verdict")]
    sums = OrderedDict((r["layer"], r) for r in recs if r.get("record") == "summary")
    out.append("## Summary")
    out.append("")
    out.append("| Layer | MUST open | MUST documented exception | SHOULD open | SHOULD documented | Passed checks |")
    out.append("|---|---|---|---|---|---|")
    for L in LAYERS:
        if L not in sums:
            continue
        le = [e for e in errs if e["layer"] == L]
        m = sum(1 for e in le if e["severity"] == "MUST" and e.get("status", "open") == "open")
        md = sum(1 for e in le if e["severity"] == "MUST" and e.get("status", "open") != "open")
        so = sum(1 for e in le if e["severity"] == "SHOULD" and e.get("status", "open") == "open")
        sd = sum(1 for e in le if e["severity"] == "SHOULD" and e.get("status", "open") != "open")
        out.append("| %s | %d | %d | %d | %d | %d |" % (LAYER_TITLE.get(L, L), m, md, so, sd, len(sums[L].get("passed", []))))
    out.append("")
    by_owner = Counter((e["owner"], e["severity"]) for e in errs if e.get("status", "open") == "open")
    if by_owner:
        out.append("Open findings by owner: " + "; ".join("%s %s %d" % (o, s, n) for (o, s), n in sorted(by_owner.items())) + ".")
        out.append("")
    ver = [r for r in recs if r.get("record") == "verdict"]
    if ver:
        v = ver[0]
        out.append("## Verdict: %s" % v["verdict"])
        out.append("")
        for line in v.get("lines", []):
            out.append(line)
        out.append("")
    comp = [r for r in recs if r.get("record") == "comparison"]
    if comp:
        c = comp[0]
        out.append("## Comparison with round %s" % c["against"][1:])
        out.append("")
        out.append("Matching key: layer, rule, model, element (element ids are stable, GEN-05). 'fixed' = in %s, not in this round; "
                   "'changed status' = same key, other severity or status; 'new' = not in %s." % (c["against"], c["against"]))
        out.append("")
        out.append("| Category | Count |")
        out.append("|---|---|")
        for k in ("fixed", "still_open", "unchanged_documented", "changed_status", "new"):
            out.append("| %s | %d |" % (k.replace("_", " "), len(c[k])))
        out.append("")
        for k, title in (("still_open", "Still open from %s" % c["against"]), ("changed_status", "Same finding, changed severity or status"),
                         ("new", "New in this round"), ("fixed", "Fixed since %s" % c["against"]),
                         ("unchanged_documented", "Unchanged documented items")):
            if not c[k]:
                continue
            out.append("### %s (%d)" % (title, len(c[k])))
            out.append("")
            out.append("| Layer | Rule | Model | Element | Owner | Severity / status | Message |")
            out.append("|---|---|---|---|---|---|---|")
            for e in c[k]:
                msg = str(e["message"]).replace("|", "\\|").replace("\n", " ")
                out.append("| %s | %s | %s | %s | %s | %s | %s |" % (e["layer"], e["rule_id"], e["model"], str(e["element"]).replace("|", "\\|"), e["owner"],
                                                                 e.get("sevstat", ""), msg[:400]))
            out.append("")
    for L in LAYERS:
        if L not in sums:
            continue
        s = sums[L]
        out.append("## %s" % LAYER_TITLE.get(L, L))
        out.append("")
        if s.get("note"):
            out.append(s["note"])
            out.append("")
        if s.get("inputs"):
            out.append("Inputs: " + "; ".join("`%s`" % i for i in s["inputs"]))
            out.append("")
        le = [e for e in errs if e["layer"] == L]
        for sev, st in (("MUST", "open"), ("MUST", "doc"), ("SHOULD", "open"), ("SHOULD", "doc")):
            sel = [e for e in le if e["severity"] == sev and ((st == "open") == (e.get("status", "open") == "open"))]
            if not sel:
                continue
            title = {("MUST", "open"): "MUST errors (open)", ("MUST", "doc"): "MUST - documented exception accepted by the orchestrator",
                     ("SHOULD", "open"): "SHOULD findings (open)", ("SHOULD", "doc"): "SHOULD findings (documented, no repair needed)"}[(sev, st)]
            out.append("### %s (%d)" % (title, len(sel)))
            out.append("")
            out.append("| Rule | Model | Element | Owner | Message |")
            out.append("|---|---|---|---|---|")
            for e in sel:
                msg = str(e["message"]).replace("|", "\\|").replace("\n", " ")
                out.append("| %s | %s | %s | %s | %s |" % (e["rule_id"], e["model"], str(e["element"]).replace("|", "\\|"), e["owner"], msg))
            out.append("")
        if s.get("passed"):
            out.append("### Passed checks (%d)" % len(s["passed"]))
            out.append("")
            for p in s["passed"]:
                out.append("- %s (n = %s)%s" % (p["check"], p.get("count", ""), (" - " + p["note"]) if p.get("note") else ""))
            out.append("")
        if s.get("not_checked"):
            out.append("### Not checked")
            out.append("")
            for p in s["not_checked"]:
                out.append("- %s" % p)
            out.append("")
    open(os.path.join(VAL, "report_%s.md" % rnd), "w", encoding="utf-8").write("\n".join(out) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--round", default="r1")
    ap.add_argument("--layer")
    ap.add_argument("--src", action="append", default=[])
    ap.add_argument("--note", default="")
    ap.add_argument("--md-only", action="store_true")
    ap.add_argument("--compare", help="earlier round to compare with, e.g. r1 (writes a comparison record)")
    ap.add_argument("--verdict", choices=["pass", "pass with documented exceptions", "fail"], help="final verdict (writes a verdict record)")
    ap.add_argument("--verdict-file", help="JSON list of markdown lines explaining the verdict")
    a = ap.parse_args()
    os.makedirs(VAL, exist_ok=True)
    jpath = os.path.join(VAL, "report_%s.json" % a.round)
    recs = load(jpath)
    if not a.md_only:
        L = a.layer
        recs = [r for r in recs if r.get("layer") != L]
        errs, passed, notc, inputs, extra = [], [], [], [], OrderedDict()
        for p in a.src:
            d = json.load(open(p, encoding="utf-8"))
            errs += [norm(e) for e in d.get("errors", []) if e.get("layer") == L]
            passed += [x for x in d.get("passed", []) if x.get("layer") == L]
            notc += [x for x in d.get("not_checked", []) if isinstance(x, str) or x.get("layer") == L]
            inputs += d.get("inputs", [])
            for k, v in (d.get("summary_extra", {}) or {}).get(L, {}).items():
                extra[k] = v
        notc = [x if isinstance(x, str) else x["what"] for x in notc]
        recs += errs
        summ = OrderedDict(record="summary", layer=L, timestamp=datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
                           counts=counts(errs), passed=passed, note=a.note, inputs=sorted(set(inputs)), not_checked=notc)
        summ.update(extra)
        recs.append(summ)
        order = {l: i for i, l in enumerate(LAYERS)}
        recs.sort(key=lambda r: (order.get(r.get("layer"), 99), 1 if r.get("record") == "summary" else 0))
        json.dump(recs, open(jpath, "w", encoding="utf-8"), indent=1, ensure_ascii=False)
        print("%s: %d error records, %d passed checks -> %s" % (L, len(errs), len(passed), jpath))
    if a.compare:
        old = [r for r in load(os.path.join(VAL, "report_%s.json" % a.compare)) if r.get("record") not in ("summary", "comparison", "verdict")]
        cur = [r for r in recs if r.get("record") not in ("summary", "comparison", "verdict")]
        key = lambda e: (e["layer"], e["rule_id"], e["model"], str(e["element"]))
        ss = lambda e: "%s %s" % (e["severity"], e.get("status", "open"))
        ok_, ck = {key(e): e for e in old}, {key(e): e for e in cur}
        comp = OrderedDict(record="comparison", against=a.compare, fixed=[], still_open=[], unchanged_documented=[], changed_status=[], new=[])
        for k, e in ok_.items():
            if k not in ck:
                comp["fixed"].append(dict(e, sevstat="was " + ss(e)))
            elif ss(ck[k]) == ss(e):
                comp["still_open" if e.get("status", "open") == "open" else "unchanged_documented"].append(dict(ck[k], sevstat=ss(e)))
            else:
                comp["changed_status"].append(dict(ck[k], sevstat="%s -> %s" % (ss(e), ss(ck[k]))))
        for k, e in ck.items():
            if k not in ok_:
                comp["new"].append(dict(e, sevstat=ss(e)))
        recs = [r for r in recs if r.get("record") != "comparison"] + [comp]
        json.dump(recs, open(jpath, "w", encoding="utf-8"), indent=1, ensure_ascii=False)
        print("comparison with %s: %s" % (a.compare, {k: len(v) for k, v in comp.items() if isinstance(v, list)}))
    if a.verdict:
        lines = json.load(open(a.verdict_file, encoding="utf-8")) if a.verdict_file else []
        recs = [r for r in recs if r.get("record") != "verdict"] + [OrderedDict(record="verdict", verdict=a.verdict, lines=lines,
                timestamp=datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"))]
        json.dump(recs, open(jpath, "w", encoding="utf-8"), indent=1, ensure_ascii=False)
        print("verdict: %s" % a.verdict)
    write_md(a.round, recs)


if __name__ == "__main__":
    main()
